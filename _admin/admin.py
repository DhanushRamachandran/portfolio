"""
Local admin for the portfolio site.

Run:   python _admin/admin.py        (or double-click _admin/start-admin.bat on Windows)
Opens: http://127.0.0.1:8787

- Edits assets/content.js through a form UI (keeps timestamped backups in _admin/backups/)
- Replaces assets/resume.pdf and uploads images to assets/img/
- Previews the site at /site/
- Publishes with git (add, commit, push) so GitHub Pages redeploys the live site

Only standard-library Python is used. The server listens on 127.0.0.1 only.
The _admin folder starts with "_" so GitHub Pages (Jekyll) does not publish it.
"""
import json
import mimetypes
import os
import re
import shutil
import subprocess
import sys
import threading
import time
import webbrowser
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import urlparse, unquote

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)                      # the website folder
CONTENT = os.path.join(ROOT, "assets", "content.js")
RESUME = os.path.join(ROOT, "assets", "resume.pdf")
IMG_DIR = os.path.join(ROOT, "assets", "img")
BACKUPS = os.path.join(HERE, "backups")
PORT = int(os.environ.get("ADMIN_PORT", "8787"))
HEADER = ('/* SITE CONTENT (generated by the admin tool: run _admin/start-admin.bat).\n'
          '   You can still hand-edit this file, but keep it valid JSON after "window.SITE =". */\n')
MAX_UPLOAD = 25 * 1024 * 1024


# ---------------------------------------------------------------- content I/O
def read_content():
    with open(CONTENT, encoding="utf-8") as f:
        src = f.read()
    start, end = src.find("{"), src.rfind("}")
    if start < 0 or end < 0:
        raise ValueError("assets/content.js has no { ... } object.")
    try:
        return json.loads(src[start:end + 1])
    except json.JSONDecodeError as e:
        raise ValueError(f"assets/content.js is not valid JSON (line {e.lineno}, col {e.colno}): {e.msg}. "
                         "Fix it by hand or restore a file from _admin/backups/.")


def write_content(data):
    for key in ("person", "projects", "writeups", "research", "experience"):
        if key not in data:
            raise ValueError(f"Missing section '{key}'.")
    ids = [p.get("id") for p in data["projects"]]
    if len(ids) != len(set(ids)) or not all(ids):
        raise ValueError("Every project needs a unique id.")
    wids = [w.get("id") for w in data["writeups"]]
    if len(wids) != len(set(wids)) or not all(wids):
        raise ValueError("Every writeup needs a unique id.")
    os.makedirs(BACKUPS, exist_ok=True)
    if os.path.exists(CONTENT):
        stamp = time.strftime("%Y%m%d-%H%M%S")
        shutil.copy2(CONTENT, os.path.join(BACKUPS, f"content-{stamp}.js"))
        old = sorted(os.listdir(BACKUPS))
        for name in old[:-30]:                       # keep the 30 newest
            os.remove(os.path.join(BACKUPS, name))
    tmp = CONTENT + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + "window.SITE = " + json.dumps(data, indent=2, ensure_ascii=False) + ";\n")
    os.replace(tmp, CONTENT)


# ---------------------------------------------------------------- git
def git(*args, timeout=120):
    try:
        r = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True,
                           timeout=timeout, encoding="utf-8", errors="replace")
        return r.returncode, (r.stdout + r.stderr).strip()
    except FileNotFoundError:
        return 127, "Git is not installed. Install it from https://git-scm.com/download/win and restart the admin."
    except subprocess.TimeoutExpired:
        return 124, "Git timed out. If a sign-in window opened, finish signing in and try again."


def ensure_gitignore():
    gi = os.path.join(ROOT, ".gitignore")
    if not os.path.exists(gi):
        with open(gi, "w", encoding="utf-8") as f:
            f.write("_admin/backups/\n__pycache__/\n*.tmp\n.DS_Store\nThumbs.db\n")


def git_status():
    code, _ = git("--version")
    if code == 127:
        return {"git": False, "message": "Git is not installed. Install it from https://git-scm.com/download/win, then restart this tool."}
    is_repo = os.path.isdir(os.path.join(ROOT, ".git"))
    if not is_repo:
        return {"git": True, "repo": False}
    code, branch = git("symbolic-ref", "--short", "HEAD")
    branch = branch if code == 0 else "main"
    _, remote = git("remote", "get-url", "origin")
    _, changes = git("status", "--porcelain")
    _, last = git("log", "-1", "--format=%h · %s · %cr")
    has_remote = bool(remote) and "No such remote" not in remote and "error" not in remote.lower()
    return {
        "git": True, "repo": True, "branch": branch,
        "remote": remote if has_remote else "",
        "changes": [l for l in changes.splitlines() if l.strip()],
        "last": last if "fatal" not in last else "",
        "pages_url": pages_url(remote) if has_remote else "",
    }


def pages_url(remote):
    m = re.search(r"github\.com[:/]([^/]+)/([^/.]+?)(?:\.git)?$", remote.strip())
    if not m:
        return ""
    user, repo = m.group(1), m.group(2)
    if repo.lower() == f"{user.lower()}.github.io":
        return f"https://{user.lower()}.github.io/"
    return f"https://{user.lower()}.github.io/{repo}/"


def git_setup(remote, name, email):
    log = []
    if not re.match(r"^(https://github\.com/|git@github\.com:)[\w.-]+/[\w.-]+?(\.git)?$", remote or ""):
        raise ValueError("Paste the repository URL from GitHub, e.g. https://github.com/DhanushRamachandran/DhanushRamachandran.github.io.git")
    if not os.path.isdir(os.path.join(ROOT, ".git")):
        code, out = git("init")
        log.append(out)
        if code:
            raise RuntimeError(out)
    git("checkout", "-B", "main")
    if name:
        git("config", "user.name", name)
    if email:
        git("config", "user.email", email)
    ensure_gitignore()
    code, out = git("remote", "get-url", "origin")
    if code == 0:
        git("remote", "set-url", "origin", remote)
        log.append(f"Updated remote origin → {remote}")
    else:
        git("remote", "add", "origin", remote)
        log.append(f"Added remote origin → {remote}")
    # If GitHub already has the site, adopt its history so the first publish is a normal update.
    has_local_commits = git("rev-parse", "--verify", "HEAD")[0] == 0
    code, out = git("fetch", "origin", "main", timeout=300)
    if code == 0 and not has_local_commits:
        git("reset", "--mixed", "origin/main")
        git("branch", "--set-upstream-to=origin/main", "main")
        log.append("Linked to the existing site on GitHub. Your local files are kept; only differences will be published.")
    elif code != 0:
        log.append("GitHub repository is empty; your first publish will upload everything.")
    return "\n".join(l for l in log if l)


def git_publish(message):
    st = git_status()
    if not st.get("git"):
        raise RuntimeError(st["message"])
    if not st.get("repo") or not st.get("remote"):
        raise RuntimeError("Connect a GitHub repository first (Publish → Connect repository).")
    ensure_gitignore()
    log = []
    code, out = git("add", "-A"); log.append("$ git add -A" + ("\n" + out if out else ""))
    code, out = git("diff", "--cached", "--quiet")
    if code == 0:
        log.append("Nothing new to commit.")
    else:
        msg = (message or "").strip() or "Update site content"
        code, out = git("commit", "-m", msg); log.append("$ git commit\n" + out)
        if code:
            if "user.email" in out or "Please tell me who you are" in out:
                raise RuntimeError("\n".join(log) + "\n\nGit needs your name and email. Fill them in under Connect repository and try again.")
            raise RuntimeError("\n".join(log))
    code, out = git("push", "-u", "origin", "HEAD:main", timeout=300); log.append("$ git push\n" + out)
    if code:
        hint = ""
        if "rejected" in out or "fetch first" in out:
            hint = ("\n\nGitHub has commits you don't have locally (for example a README created on github.com). "
                    "Use 'Sync from GitHub' and publish again.")
        elif "Authentication" in out or "could not read Username" in out or "403" in out:
            hint = "\n\nGit couldn't sign in to GitHub. Run 'git push' once from a terminal in this folder to sign in, then use Publish again."
        raise RuntimeError("\n".join(log) + hint)
    return "\n".join(log)


def git_pull():
    code, out = git("pull", "--rebase", "--allow-unrelated-histories", "-X", "theirs", "origin", "main", timeout=300)
    if code:
        git("rebase", "--abort")
        raise RuntimeError("$ git pull --rebase\n" + out)
    return "$ git pull --rebase\n" + out


# ---------------------------------------------------------------- HTTP
class Handler(BaseHTTPRequestHandler):
    server_version = "PortfolioAdmin/1.0"

    def log_message(self, fmt, *args):
        sys.stderr.write("  %s\n" % (fmt % args))

    # -- helpers
    def send(self, code, body, ctype="application/json; charset=utf-8"):
        if isinstance(body, (dict, list)):
            body = json.dumps(body, ensure_ascii=False)
        if isinstance(body, str):
            body = body.encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def local_only(self):
        host = (self.headers.get("Host") or "").split(":")[0]
        return host in ("127.0.0.1", "localhost")

    def body(self):
        n = int(self.headers.get("Content-Length") or 0)
        if n > MAX_UPLOAD:
            raise ValueError("File is larger than 25 MB.")
        return self.rfile.read(n)

    def serve_file(self, path):
        if not os.path.isfile(path):
            return self.send(404, {"error": "Not found"})
        ctype = mimetypes.guess_type(path)[0] or "application/octet-stream"
        if ctype.startswith("text/") or ctype in ("application/javascript",):
            ctype += "; charset=utf-8"
        with open(path, "rb") as f:
            self.send(200, f.read(), ctype)

    # -- routes
    def do_GET(self):
        if not self.local_only():
            return self.send(403, {"error": "Local access only"})
        url = urlparse(self.path)
        p = unquote(url.path)
        try:
            if p in ("/", "/admin", "/admin/"):
                return self.serve_file(os.path.join(HERE, "admin.html"))
            if p == "/api/content":
                return self.send(200, read_content())
            if p == "/api/git/status":
                return self.send(200, git_status())
            if p == "/api/images":
                files = sorted(os.listdir(IMG_DIR)) if os.path.isdir(IMG_DIR) else []
                return self.send(200, ["assets/img/" + f for f in files])
            if p == "/api/resume":
                ok = os.path.exists(RESUME)
                return self.send(200, {"exists": ok, "size": os.path.getsize(RESUME) if ok else 0,
                                       "modified": time.strftime("%Y-%m-%d %H:%M", time.localtime(os.path.getmtime(RESUME))) if ok else ""})
            if p == "/site" :
                self.send_response(302); self.send_header("Location", "/site/"); self.end_headers(); return
            if p.startswith("/site/"):
                rel = p[len("/site/"):] or "index.html"
                full = os.path.normpath(os.path.join(ROOT, rel))
                if not full.startswith(ROOT) or os.sep + "_admin" in full[len(ROOT):] or os.sep + ".git" in full[len(ROOT):]:
                    return self.send(403, {"error": "Forbidden"})
                if os.path.isdir(full):
                    full = os.path.join(full, "index.html")
                return self.serve_file(full)
            return self.send(404, {"error": "Not found"})
        except Exception as e:  # noqa: BLE001
            return self.send(500, {"error": str(e)})

    def do_POST(self):
        # Custom header blocks cross-site form posts (browsers can't add it without CORS approval).
        if not self.local_only() or self.headers.get("X-Admin") != "1":
            return self.send(403, {"error": "Local access only"})
        p = urlparse(self.path).path
        try:
            if p == "/api/content":
                write_content(json.loads(self.body().decode("utf-8")))
                return self.send(200, {"ok": True, "saved": time.strftime("%H:%M:%S")})
            if p == "/api/resume":
                data = self.body()
                if not data.startswith(b"%PDF"):
                    raise ValueError("That file isn't a PDF.")
                with open(RESUME, "wb") as f:
                    f.write(data)
                return self.send(200, {"ok": True})
            if p == "/api/image":
                name = os.path.basename(unquote(self.headers.get("X-Filename") or "image"))
                name = re.sub(r"[^\w.-]+", "-", name).strip("-").lower() or "image"
                if not re.search(r"\.(png|jpe?g|gif|webp|svg)$", name):
                    raise ValueError("Use a PNG, JPG, GIF, WebP or SVG image.")
                os.makedirs(IMG_DIR, exist_ok=True)
                with open(os.path.join(IMG_DIR, name), "wb") as f:
                    f.write(self.body())
                return self.send(200, {"ok": True, "path": "assets/img/" + name})
            if p == "/api/git/setup":
                d = json.loads(self.body() or b"{}")
                return self.send(200, {"ok": True, "log": git_setup(d.get("remote", "").strip(), d.get("name", "").strip(), d.get("email", "").strip())})
            if p == "/api/git/publish":
                d = json.loads(self.body() or b"{}")
                return self.send(200, {"ok": True, "log": git_publish(d.get("message", ""))})
            if p == "/api/git/pull":
                return self.send(200, {"ok": True, "log": git_pull()})
            return self.send(404, {"error": "Not found"})
        except Exception as e:  # noqa: BLE001
            return self.send(400, {"error": str(e)})


def main():
    if not os.path.exists(CONTENT):
        sys.exit(f"Can't find {CONTENT}. Keep the _admin folder inside the website folder.")
    try:
        srv = ThreadingHTTPServer(("127.0.0.1", PORT), Handler)
    except OSError:
        print(f"Port {PORT} is busy — the admin is probably already running. Opening it.")
        webbrowser.open(f"http://127.0.0.1:{PORT}/")
        return
    url = f"http://127.0.0.1:{PORT}/"
    print(f"\n  Portfolio admin running at {url}\n  Website folder: {ROOT}\n  Close this window (or press Ctrl+C) to stop.\n")
    if "--no-browser" not in sys.argv:
        threading.Timer(0.6, lambda: webbrowser.open(url)).start()
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
